"""Past-case and other CPU sources rebuilt per fold from the original code (RUN_PLAN §3.6; "rerun everything").

The frozen embedding_push sources (similar-case citations with every key, article profiles, learned case
similarity, document expansion, the lexical fusions, the fine-tuned e5 query tower) are regenerated by running the
original stages unchanged through ``uol.round3.rebuild`` (the Round 3 Phase 0 rebuild driver; same stage order and
arguments as its RUN_LEDGER), with the profile's inputs and a writable output folder:

* ``UOL_FINAL_SOURCES=rebuilt`` makes ``embedding_push.common.RUN`` / ``SCORES`` point to ``<work>/ep_rebuild``;
  selections, caches and score files of the stages go there; the frozen copies stay untouched in ``data/ep_run``;
* every result scored in that profile is stored under ``<system>@rebuilt``, beside the frozen copy;
* GPU-trained stages (``finetune_dense`` for ft_e5_q, ``case_sim`` keys) run their training subprocess with this
  Python (``GPU_PYTHON`` redirected) and the model snapshots of ``<work>/models``.

Stages only run on a development-only release (the bundle): on the full v11 release they would score test rows,
so ``run_stage`` refuses when the active release has any lockbox row.

    python -m uol.final rebuild-stage base all                    # one stage (what the plan jobs call)
    python -m uol.final g1 --route rebuild                        # rebuilt vs frozen copies (G1, after the stages)
"""
