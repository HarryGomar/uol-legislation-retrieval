def rebuilt_root(prof=None) -> Path:
    from uol.embedding_push import common as ep
    return Path(ep.RUN)


def prepare_folder(prof) -> None:
    """Seed ``<work>/ep_rebuild`` with what the stages read but do not produce (frozen GPU encoder outputs), through
    ``copy_frozen`` so a variant release with more rows gets them mapped by query id (added rows: -inf)."""
    root = rebuilt_root(prof)
    for sid in FROZEN_ONLY:
        if (prof.path("ep_run") / "scores" / sid).exists() and not (root / "scores" / sid / "manifest.json").exists():
            copy_frozen(sid)


def patch_runtime(prof) -> dict[str, str]:
    """Redirect the stage modules' hard-coded GPU interpreter and model folders, and route their subprocesses."""
    from uol.round3 import rebuild as R
    applied: dict[str, str] = {}
    models = prof.work / "models"
    for name, (_, _, folder) in MODELS.items():
        if (models / folder).exists():
            R.MODEL_DIRS[name] = models / folder
            applied[f"round3.rebuild.MODEL_DIRS.{name}"] = str(models / folder)
    R.LEDGER = prof.work / "round3_state" / "RUN_LEDGER.jsonl"
    for mod in ("uol.embedding_push.finetune_dense", "uol.embedding_push.case_sim"):
        m = __import__(mod, fromlist=["x"])
        m.GPU_PYTHON = Path(sys.executable)
        applied[f"{mod}.GPU_PYTHON"] = sys.executable
    # Order matters: this wrapper goes first, round3.rebuild's wrapper (embedding_push.X -> round3.rebuild X) is then
    # installed on top of it, so a child first becomes "round3.rebuild X" and then "uol.final rebuild-stage X".
    orig = subprocess.run

    def run(cmd, *a, **k):                    # child stages re-enter through this CLI so they get the same profile
        if isinstance(cmd, (list, tuple)):
            cmd = list(cmd)
            for i in range(len(cmd) - 1):
                if cmd[i] == "-m" and cmd[i + 1] == "uol.round3.rebuild":
                    cmd[i + 1:i + 2] = ["uol.final", "rebuild-stage"]
                    break
        env = dict(k.pop("env", None) or os.environ)
        env.update({k_: os.environ[k_] for k_ in ("UOL_FINAL_DATA", "UOL_FINAL_SOURCES", "UOL_FINAL_WORK", "UOL_FINAL_STORE")
                    if k_ in os.environ})
        env["PYTHONPATH"] = os.pathsep.join(p for p in (env.get("PYTHONPATH"), str(Path(__file__).resolve().parents[2])) if p)
        return orig(cmd, *a, env=env, **k)
    if not getattr(subprocess.run, "_uol_final", False):
        run._uol_final = True
        subprocess.run = run
        R.patch_paths()                       # wraps ours (ours has no _round3 attribute)
    # finetune_dense copies facts_to_law.dense.MODEL_DIR into E5_MODEL_DIR at import, which happened above, before
    # patch_paths moved MODEL_DIR to the downloaded snapshot: follow it (21 Oct 2026).
    fd = sys.modules.get("uol.embedding_push.finetune_dense")
    if fd is not None:
        from uol.facts_to_law import dense
        from uol.embedding_push import common as ep_common
        if Path(fd.E5_MODEL_DIR) != Path(dense.MODEL_DIR):
            fd.E5_MODEL_DIR = dense.MODEL_DIR
            applied["embedding_push.finetune_dense.E5_MODEL_DIR"] = str(dense.MODEL_DIR)
        if Path(fd.BGE_MODEL_DIR) != Path(ep_common.BGE_DIR):
            fd.BGE_MODEL_DIR = ep_common.BGE_DIR
            applied["embedding_push.finetune_dense.BGE_MODEL_DIR"] = str(ep_common.BGE_DIR)
    applied.update(guard_empty_groups())
    prof.patches.update(applied)
    return applied


def guard_empty_groups() -> dict[str, str]:
    """The bundle is development-only, so the stages' ``lockbox`` scoring group has no row to score (its selection
    still runs on all dev rows, as in the frozen run). Dense and BM25 similarities of zero rows are empty arrays, but
    scikit-learn's TF-IDF ``transform`` refuses an empty list (22 Oct 2026, devn_rb_knn: ``knn_lexc_spec`` lockbox,
    "Found array with 0 sample(s)"; every chain's rb_knn and rb_proto_tfidf would follow). For zero evaluation rows
    the two character / word TF-IDF scorers of memory_proto return the empty block of the right width; with any row
    they call the original unchanged, so every non-empty group computes exactly what it did."""
    import numpy as np
    from uol.embedding_push import memory_proto as mp
    out: dict[str, str] = {}
    if not getattr(mp.sim_char, "_uol_final", False):
        orig_char = mp.sim_char

        def sim_char(eval_rows, mem):
            if len(eval_rows) == 0:
                return np.zeros((0, len(mem.rows)), dtype=np.float32)
            return orig_char(eval_rows, mem)
        sim_char._uol_final, sim_char.__wrapped__ = True, orig_char
        mp.sim_char = sim_char
    out["uol.embedding_push.memory_proto.sim_char"] = "empty block for zero evaluation rows"
    if not getattr(mp.proto_sparse_block, "_uol_final", False):
        orig_ps = mp.proto_sparse_block

        def proto_sparse_block(train_rows, eval_rows, *a, **k):
            if len(eval_rows) == 0:
                return np.empty((0, mp.n_candidates()), dtype=np.float32)
            return orig_ps(train_rows, eval_rows, *a, **k)
        proto_sparse_block._uol_final, proto_sparse_block.__wrapped__ = True, orig_ps
        mp.proto_sparse_block = proto_sparse_block
    out["uol.embedding_push.memory_proto.proto_sparse_block"] = "empty block for zero evaluation rows"
    return out


def run_stage(argv: Sequence[str]) -> int:
    prof = context.active()
    from uol.embedding_push import common as ep
    if prof.sources != "rebuilt":
        raise RuntimeError("rebuild-stage needs UOL_FINAL_SOURCES=rebuilt (outputs go to <work>/ep_rebuild)")
    if len(ep.lockbox_rows()):
        raise guard.TestSetRefused("the original stages score every release row; they run on the development-only "
                                   "bundle only, never on the full v11 release")
    guard.check_release_dev_only(ep.release().queries, list(ep.roles()))
    prepare_folder(prof)
    patch_runtime(prof)
    context.install_worker_init(prof)          # pool workers re-activate this profile (21 Oct 2026)
    from uol.round3 import rebuild as R
    return int(R.main(list(argv)) or 0)


def sources() -> list[str]:
    """Full sources of the frozen feature table (the rebuilt copies are compared one by one in G1)."""
    meta = json.loads((context.active().path("ep_run") / "fusion/features/meta.json").read_text(encoding="utf-8"))
    return [s["id"] for s in meta["sources"] if s["kind"] == "full"]


def model_download(dest: Path) -> dict[str, Any]:
    """Run computer: the pinned snapshots the GPU-trained stages need (network: Hugging Face, pinned revisions)."""
    out = {}
    from huggingface_hub import snapshot_download
    for name, (repo, rev, folder) in MODELS.items():
        p = snapshot_download(repo, revision=rev, local_dir=str(Path(dest) / folder),
                              allow_patterns=["*.json", "*.safetensors", "*.txt", "*.model", "tokenizer*", "sentencepiece*",
                                              "pytorch_model.bin", "1_Pooling/*", "colbert_linear.pt", "sparse_linear.pt"])
        out[name] = p
    return out


GPU_TRAINED = ("ft_e5_q", "knn_casesim_e5", "knn_casesim_e5_all", "proto_casesim_e5")


def copy_frozen(sid: str) -> Path | None:
    """Copy one frozen source into the active (rebuilt) score folder. A full score file with one row per release row
    is copied as is; a variant release with other rows gets each row by query id from the bundle rows, and rows the
    bundle does not have get -inf (no score from that source). Pair files (ColBERT) are copied whole."""
    import shutil
    import numpy as np
    from uol.embedding_push import common as ep
    prof = context.active()
    src = prof.path("ep_run") / "scores" / sid
    dst = Path(ep.SCORES) / sid
    if not src.exists():
        return None
    if not (src / "scores.npy").exists():
        shutil.copytree(src, dst, dirs_exist_ok=True)
        return dst
    d = ep.release()
    dst.mkdir(parents=True, exist_ok=True)
    F = np.load(src / "scores.npy", mmap_mode="r")
    if F.shape[0] == len(d.queries):
        shutil.copy2(src / "scores.npy", dst / "scores.npy")
    else:
        ids_file = prof.data_dir / context.BUNDLE_LAYOUT["qwen8b"] / "query_ids.json" if prof.data_dir else None
        if ids_file is None or not ids_file.exists():
            raise RuntimeError(f"{sid}: {F.shape[0]} frozen rows for {len(d.queries)} release rows and no bundle row ids")
        pos = {q: i for i, q in enumerate(json.loads(ids_file.read_text(encoding="utf-8")))}
        M = np.lib.format.open_memmap(dst / "scores.npy", mode="w+", dtype=np.float32, shape=(len(d.queries), F.shape[1]))
        for i, q in enumerate(d.queries):
            M[i] = F[pos[q.query_id]] if q.query_id in pos else -np.inf
        M.flush()
        del M
    m = json.loads((src / "manifest.json").read_text(encoding="utf-8"))
    m["scores_sha256"] = ep.sha256_file(dst / "scores.npy")
    m["copied_frozen"] = True
    (dst / "manifest.json").write_text(json.dumps(m, indent=1), encoding="utf-8")
    return dst


def copy_frozen_gpu_trained() -> dict[str, Any]:
    """Chains without GPU stages (G1 on v11 labels, DEV-T, DEV-B, DEV-N): the GPU-trained sources are copied from
    the frozen run (rows the variant adds get -inf, i.e. no score from that source). The copies are reported, not
    gated, and they carry the frozen training data (the DEV-T caveat: trained across time)."""
    from uol.embedding_push import common as ep
    out = {}
    for sid in GPU_TRAINED + FROZEN_ONLY:
        if (Path(ep.SCORES) / sid / "manifest.json").exists():
            continue
        dst = copy_frozen(sid)
        if dst is not None:
            out[sid] = str(dst)
    return out
