"""Phase 0 step 9: reranker setup and throughput on the remote RTX 5080 (writes MODELS.md inputs).

Pairs: 20 dev rows (the first 20 of the L2 pilot sample) x their LTR_emb_hgb top 20 = 400 (masked Hechos, public
article text; no labels, no lockbox rows). The job downloads each model on the worker at a pinned revision.

    python -m uol.round3.rerank_setup submit       # blocks until the worker returns; run in the background
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from uol.round3 import common as C
from uol.round3 import features, gpu_remote, l2_luna

JOB_DIR = C.RUN / "phase0" / "rerank_setup"
ENTRY = Path(__file__).resolve().parent / "gpu_jobs" / "rerank_bench.py"
INSTRUCTION = ("Given the facts of a Mexican court case, judge whether the federal statutory article is one the court "
               "would cite to decide the case.")
TASK = {"instruction": INSTRUCTION, "max_query_tokens": 384, "max_doc_tokens": 256, "batch_sizes": [8, 16, 32],
        "models": [{"name": "qwen3_rr_0.6b"}, {"name": "bge_rr_v2_m3"}, {"name": "qwen3_rr_4b"},
                   {"name": "qwen3_rr_8b", "quant": "8bit"}, {"name": "qwen3_rr_8b", "quant": "4bit"}]}


def build_inputs() -> dict[str, Path]:
    rows = l2_luna.pilot_rows()[:20]
    if np.isin(rows, C.lockbox_rows()).any():
        raise PermissionError("dev rows only")
    d = C.release()
    top = features.ltr_topk("LTR_emb_hgb", rows, 20)
    JOB_DIR.mkdir(parents=True, exist_ok=True)
    pairs = JOB_DIR / "pairs.jsonl"
    with pairs.open("w", encoding="utf-8") as f:
        for qi, (r, cands) in enumerate(zip(rows, top)):
            for c in cands:
                f.write(json.dumps({"pid": f"q{qi:02d}_{int(c)}", "query": d.queries[int(r)].text,
                                    "doc": d.candidate_texts[int(c)]}, ensure_ascii=False) + "\n")
    task = JOB_DIR / "task.json"
    task.write_text(json.dumps(TASK, indent=1), encoding="utf-8")
    C.write_json(JOB_DIR / "pairs_index.json", {"rows": rows, "candidates": top.tolist()})
    return {"pairs.jsonl": pairs, "task.json": task}


CARDS = {  # Hugging Face API, read 2026-10-14 (createdAt, licence from the card metadata)
    "qwen3_rr_0.6b": ("Qwen/Qwen3-Reranker-0.6B", "e61197ed45024b0ed8a2d74b80b4d909f1255473", "apache-2.0", "2025-05-29", 595776512),
    "qwen3_rr_4b": ("Qwen/Qwen3-Reranker-4B", "22e683669bc0f0bd69640a1354a6d0aebcfeede5", "apache-2.0", "2025-06-03", 4021784576),
    "qwen3_rr_8b": ("Qwen/Qwen3-Reranker-8B", "77d193c791ed757ca307ee72715aa132723da912", "apache-2.0", "2025-05-29", 8188548096),
    "bge_rr_v2_m3": ("BAAI/bge-reranker-v2-m3", "953dc6f6f85a1b2dbfca4c34a2796e7dde08d41e", "apache-2.0", "2024-03-15", 567755777),
}


def report(jobs: list[str]) -> str:
    from scipy.stats import spearmanr
    benches = {}
    for j in jobs:
        out = gpu_remote.LOCAL_JOBS / j / "remote" / "outputs"
        if (out / "bench.json").exists():
            benches[j] = (json.loads((out / "bench.json").read_text(encoding="utf-8")), out)
    L = ["# Round 3 reranker models (Phase 0 step 9)", "",
         f"Generated by `python -m uol.round3.rerank_setup report`. Benchmark pairs: 400 dev pairs (20 dev rows x their "
         f"LTR_emb_hgb top 20; masked Hechos ≤ {TASK['max_query_tokens']} tokens, article text ≤ {TASK['max_doc_tokens']} "
         "tokens; no labels, no lockbox). Worker: RTX 5080 16 GB, torch 2.11.0+cu128, transformers 5.17.0. "
         "Models were downloaded on the worker at the pinned revisions.", "",
         "## Model cards", "", "| model | Hugging Face id | revision | licence | created | parameters |",
         "|---|---|---|---|---|---:|"]
    for k, (repo, rev, lic, date, n) in CARDS.items():
        L.append(f"| {k} | `{repo}` | `{rev[:12]}` | {lic} | {date} | {n / 1e9:.2f}B |")
    for j, (b, out) in benches.items():
        L += ["", f"## Throughput: job `{j}`", "",
              "| model | precision | load s | peak GPU GiB | " + " | ".join(f"pairs/s @bs{bs}" for bs in TASK["batch_sizes"]) + " | error |",
              "|---|---|---:|---:|" + "---:|" * len(TASK["batch_sizes"]) + "---|"]
        for k, r in b["models"].items():
            thr = r.get("throughput", {})
            cells = [str(thr.get(str(bs), {}).get("pairs_per_second", "–")) for bs in TASK["batch_sizes"]]
            prec = r.get("quant") or ("bf16")
            L.append(f"| {k} | {prec} | {r.get('load_seconds', '–')} | {r.get('peak_gpu_gib', '–')} | " + " | ".join(cells)
                     + f" | {r.get('error', '')[:80]} |")
        scores = {k: json.loads((out / f"scores_{k}.json").read_text(encoding="utf-8"))
                  for k in b["models"] if (out / f"scores_{k}.json").exists()}
        if len(scores) > 1:
            pids = sorted(next(iter(scores.values())))
            ks = list(scores)
            L += ["", "Spearman correlation of scores on the 400 pairs:", "", "| | " + " | ".join(ks) + " |",
                  "|---|" + "---:|" * len(ks)]
            for x in ks:
                L.append(f"| {x} | " + " | ".join(f"{spearmanr([scores[x][p] for p in pids], [scores[y][p] for p in pids])[0]:.3f}"
                                                for y in ks) + " |")
    text = "\n".join(L) + "\n"
    (C.REPORTS / "MODELS.md").write_text(text, encoding="utf-8")
    return text


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["submit", "report"])
    ap.add_argument("--job-id", default="phase0_rerank_bench_s1")
    ap.add_argument("--jobs", nargs="*", default=["phase0_rerank_bench_s1", "phase0_rerank_bench_s2"])
    a = ap.parse_args()
    if a.command == "report":
        print(report(a.jobs)[:4000])
        return 0
    inputs = build_inputs()
    start = C.utc()
    C.ledger({"kind": "job_start", "job_id": a.job_id, "command": " ".join(sys.argv), "gpu": "remote RTX 5080"})
    receipt = gpu_remote.submit(a.job_id, ENTRY, inputs, expected_outputs=["bench.json"])
    C.ledger({"kind": "job_end", "job_id": a.job_id, "start_utc": start, "end_utc": C.utc(),
              "exit_code": receipt.get("exit_code"), "receipt": {k: receipt.get(k) for k in ("seconds", "env", "outputs")}})
    print(json.dumps(receipt, indent=1)[:3000])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
