"""F2.4 (D76 redesign, write-ch2): the catalogue in the space of Qwen3-Embedding-8B, five laws coloured.

Replaces F9 (f09_map.py), which stays only as the earlier version. Source: the saved 2-D UMAP of all 39,178
Qwen3-Embedding-8B article vectors (E1, arms/E1_structure/umap_articles.npy) and the statute graph's article-to-law
index (phase2/statute_graph/graph.npz, key 'inst'), exactly as f09_map.py reads them. No embedding or projection is
recomputed.

Output: thesis/figures/F2_4_map_points.pdf (points only, rasterised, no text) and thesis/figures/F2_4_map.tex (a
tikzpicture that places the points and draws each law's label in the thesis body font at the densest region of that
law, with a thin leader). The chapter wraps F2_4_map.tex in its figure float and caption.

    py -3.12 -m uol.thesis_figures.f2_4_map
"""
from __future__ import annotations

import matplotlib.pyplot as plt
import numpy as np

from uol.thesis_figures import common as C
from uol.thesis_figures.f09_map import GRAPH, UMAP, law_titles

OUT_DIR = C.ROOT / "thesis" / "figures"
W_CM = 12.46                     # full text width; the map box is the central square, labels sit at the sides
MAP_CM = 7.8                     # side of the square that holds the points (equal aspect)
# law index (graph 'inst') -> (label, colour, side of the label: -1 left, +1 right, label height in cm in the square)
# The leader starts at the law's densest region (histogram smoothed over 5 x 5 of 24 x 24 bins). For the Commercial
# Code that is its own island (861 of its 1,641 articles); most of the rest lie beside the Civil Code.
LAWS = {
    44: ("Civil Code", "0072B2", +1, 6.3),
    45: ("Commerce Code", "E69F00", -1, 0.9),
    134: ("Labour Law", "56B4E9", -1, 6.2),
    67: ("Ley de Amparo", "CC79A7", +1, 4.4),
    52: ("Constitution", "006648", -1, 3.3),
}
REST = "#d0d0d0"


def _densest(u: np.ndarray, x0: float, y0: float, span: float, bins: int = 24, k: int = 2) -> tuple[float, float]:
    from numpy.lib.stride_tricks import sliding_window_view
    hist, xe, ye = np.histogram2d(u[:, 0], u[:, 1], bins=bins, range=[[x0, x0 + span], [y0, y0 + span]])
    smooth = sliding_window_view(np.pad(hist, k), (2 * k + 1, 2 * k + 1)).sum(axis=(2, 3))
    bx, by = np.unravel_index(np.argmax(smooth), smooth.shape)
    return (xe[bx] + xe[bx + 1]) / 2, (ye[by] + ye[by + 1]) / 2


def build() -> dict:
    C.style()
    U = np.load(C.ROOT / UMAP)
    inst = np.load(C.ROOT / GRAPH)["inst"].astype(int)
    assert len(inst) == len(U) == 39178, (len(inst), len(U))
    titles = law_titles(inst)
    lo, hi = np.percentile(U, 2.0, axis=0), np.percentile(U, 98.5, axis=0)
    span = float(max(hi - lo)) * 1.06
    cx, cy = (lo + hi) / 2
    x0, y0 = cx - span / 2, cy - span / 2

    fig = plt.figure(figsize=(MAP_CM / 2.54, MAP_CM / 2.54))
    ax = fig.add_axes([0, 0, 1, 1])
    rest = ~np.isin(inst, list(LAWS))
    ax.scatter(U[rest, 0], U[rest, 1], s=0.6, c=REST, linewidths=0, rasterized=True)
    for li, (_, col, _, _) in LAWS.items():
        m = inst == li
        ax.scatter(U[m, 0], U[m, 1], s=1.4 if m.sum() > 500 else 2.4, c="#" + col, linewidths=0, rasterized=True)
    ax.set_xlim(x0, x0 + span)
    ax.set_ylim(y0, y0 + span)
    ax.axis("off")
    pts = OUT_DIR / "F2_4_map_points.pdf"
    fig.savefig(pts, dpi=600, metadata={"CreationDate": None})
    plt.close(fig)

    # TikZ overlay: map square centred, labels at the sides with leaders to each law's densest region.
    left = (W_CM - MAP_CM) / 2
    lines = [
        "% F2.4 for 2.2.4: the catalogue in the space of an embedding model. Generated by uol.thesis_figures.f2_4_map;",
        "% do not edit by hand. Points: F2_4_map_points.pdf (saved E1 UMAP of the Qwen3-Embedding-8B article vectors,",
        f"% {UMAP}; laws from {GRAPH} 'inst'). No embedding or projection was recomputed.",
        "% Laws coloured (graph index, articles): " + "; ".join(
            f"{li} {titles[li][:40]} ({int((inst == li).sum())})" for li in LAWS),
        "\\begin{tikzpicture}[x=1cm, y=1cm, every node/.append style={inner sep=0pt, outer sep=0pt}]",
        "  \\definecolor{f24lead}{HTML}{8C8C8C}%",
        f"  \\node[anchor=south west] at ({left:.3f},0) {{\\includegraphics[width={MAP_CM}cm]{{F2_4_map_points.pdf}}}};",
    ]
    for li, (lab, col, side, ly) in LAWS.items():
        m = inst == li
        px, py = _densest(U[m], x0, y0, span)
        near = U[m][np.argmin(((U[m] - [px, py]) ** 2).sum(axis=1))]     # snap to an actual article of the law
        px, py = float(near[0]), float(near[1])
        X = left + (px - x0) / span * MAP_CM
        Y = (py - y0) / span * MAP_CM
        lx = left - 0.15 if side < 0 else left + MAP_CM + 0.15
        anchor = "east" if side < 0 else "west"
        align = "right" if side < 0 else "left"
        text = {"Ley de Amparo": "Ley de\\\\Amparo", "Commerce Code": "Commerce\\\\Code"}.get(lab, lab)
        lines += [
            f"  \\definecolor{{f24c{li}}}{{HTML}}{{{col}}}%",
            f"  \\draw[f24lead, line width=0.4pt] ({X:.3f},{Y:.3f}) -- ({lx:.3f},{ly:.3f});",
            f"  \\fill[white] ({X:.3f},{Y:.3f}) circle (1.7pt); \\fill[f24c{li}] ({X:.3f},{Y:.3f}) circle (1.2pt);",
            f"  \\node[anchor={anchor}, align={align}, font=\\scriptsize\\bfseries, text=f24c{li}] at ({lx + (-0.08 if side < 0 else 0.08):.3f},{ly:.3f}) {{{text}}};",
        ]
    lines += [f"  \\path (0,0) rectangle ({W_CM},{MAP_CM});", "\\end{tikzpicture}", ""]
    (OUT_DIR / "F2_4_map.tex").write_text("\n".join(lines), encoding="utf-8")
    return {"points": str(pts), "tex": str(OUT_DIR / "F2_4_map.tex")}


if __name__ == "__main__":
    print(build())
