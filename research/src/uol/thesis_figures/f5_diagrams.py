from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RESULTS = ROOT / "research" / "programs" / "final_results_20261102" / "results.json"
OUT = ROOT / "thesis" / "figures"
SRC = ROOT / "src" / "uol"
EXAMPLE = "sjf:tesis:2028281:hechos"          # the running example (scripts/final_results.py EXAMPLE)


def _const(path: Path, name: str) -> int:
    m = re.search(rf"^{name}\s*=\s*(\d+)", path.read_text(encoding="utf-8"), re.M)
    if not m:
        raise ValueError(f"{name} not found in {path}")
    return int(m.group(1))


def facts() -> dict:
    res = json.loads(RESULTS.read_text(encoding="utf-8"))
    rk = res["system"]["ranker"]
    prompt = (SRC / "round3" / "prompts" / "closedbook_rank20.txt").read_text(encoding="utf-8")
    n_list = int(re.search(r"Da exactamente (\d+) art", prompt).group(1))
    windows = (SRC / "final" / "external.py").read_text(encoding="utf-8")
    # rerank_orders: window A = ranks 11-30, window B = ranks 1-10 plus A's first 10
    assert "top[r][10:30]" in windows and "top[r][:10] + a[" in windows, "window layout changed in external.rerank_orders"
    receipt = json.loads((ROOT / "experiments" / "runs" / "footing_20261101" / "dev" / "store" / "receipts"
                          / "rt_lm_tesis__DEV.json").read_text(encoding="utf-8"))
    one_order = res["system"]["settings"]["frozen"]["passes"] == ["fwd"]      # PLAN addendum 22: the frozen settings
    ex = res["experiments"]["examples"][EXAMPLE]
    return {"catalogue": int(receipt["release"]["candidates"]), "sources": int(rk["sources"]), "inputs": int(rk["inputs"]),
            "top": int(rk["top_per_source"]), "pool": int(round(rk["pool_per_case"], -1)), "n_list": n_list,
            "rrf_k": _const(SRC / "final" / "llm_agents.py", "RRF_K"), "depth": _const(SRC / "final" / "external.py", "TOP"),
            "window": 20, "one_order": one_order,
            "ex": {k: int(ex[k]) for k in ("alone", "ranker", "merged", "system")}}


def thousands(n: int) -> str:
    return f"{n:,}"


