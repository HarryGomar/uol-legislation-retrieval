def fill(tpl: str, f: dict) -> str:
    ex = f["ex"]
    clip = lambda r, n: r if 1 <= r <= n else 0          # a rank beyond the strip's bars is not drawn
    vals = {"NLIST": f["n_list"], "SOURCES": f["sources"], "CAT": thousands(f["catalogue"]), "TOP": f["top"],
            "POOL": thousands(f["pool"]), "INPUTS": f["inputs"], "RRFK": f["rrf_k"], "DEPTH": f["depth"],
            "WINDOW": f["window"], "ORDERS": "in one order" if f["one_order"] else "in two orders",
            "ORDERNOTE": "one order, forward" if f["one_order"] else "two orders",
            "EXALONE": clip(ex["alone"], f["n_list"]), "EXRANKER": clip(ex["ranker"], 38), "EXRANKERTEN": clip(ex["ranker"], 10),
            "EXMERGED": clip(ex["merged"], 40), "EXSYSTEM": clip(ex["system"], 10)}
    out = tpl
    for k, v in vals.items():
        out = out.replace(f"<<{k}>>", str(v))
    assert "<<" not in out, re.findall(r"<<\w+>>", out)
    return out


def main() -> int:
    f = facts()
    (OUT / "F5_arch.tex").write_text(fill(ARCH, f), encoding="utf-8")
    (OUT / "F5_arch_float.tex").write_text(ARCH_FLOAT, encoding="utf-8")
    (OUT / "F5_2_llm_windows.tex").write_text(fill(WINDOWS, f), encoding="utf-8")
    print(json.dumps(f))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
