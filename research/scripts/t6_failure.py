"""Table 6.x: one miss at the first position, a development case whose first suggestion is another article of the cited law
(D203, 4 Nov 2026). The case is fixed by its id; its facts come from the prototype bundle, the system's first three
suggestions from its stored top-200, the cited article from its per-case file. Writes ``thesis/tables/T6_failure.tex``.

The case was chosen among the development cases with one cited article whose first suggestion lies in the cited law, for
short facts and a cited article ranked second; ``scripts/t5_output.py`` supplies the article text and the supporting tesis
(none for any of the three here).

    py -3.12 scripts/t6_failure.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
import t5_output as T  # noqa: E402
from uol.analysis_c.common import load_catalogue  # noqa: E402
from uol.prototype import signals as S  # noqa: E402

CASE = "sjf:tesis:2025181:hechos"
OUT = ROOT / "thesis/tables/T6_failure.tex"
TOP = 3


def main() -> None:
    sid = json.loads(T.RESULTS.read_text(encoding="utf-8"))["system"]["dev_system"]
    run = T.STORE / sid / "DEV"
    cat = load_catalogue()
    top = pd.read_parquet(run / "top200.parquet")
    top = top[top.query_id == CASE].sort_values("rank").head(TOP)
    case = pd.read_parquet(run / "per_case.parquet")
    cited = {int(i) for i in re.findall(r"\d+", str(case.loc[case.query_id == CASE, "positive_idx"].iloc[0]))}
    ids = [cat.candidate_ids[int(i)] for i in top.candidate_idx]
    sup = T.support(CASE, ids)
    if any(sup[c] for c in ids):
        raise SystemExit("a past tesis now supports one of the three; the text says none does")
    dev = S.Dev.load()
    facts = T.tex(" ".join(dev.texts[dev.by_query[CASE]].split()))
    rows = []
    for _, r in top.iterrows():
        i = int(r.candidate_idx)
        art = cat.candidate_ids[i].split("#articulo=", 1)[1]
        law = T.law_name(cat.law_titles[int(cat.law[i])])
        label = rf"\textbf{{{art}}}" if i in cited else art
        rows.append(f"    {int(r['rank'])} & {label}, {law} & {T.opening(sup['_snippets'][cat.candidate_ids[i]])} \\\\")
    record = CASE.split(":")[2]
    body = "\n".join([
        "% Generated by scripts/t6_failure.py; do not edit by hand.",
        f"% Source: {run.relative_to(ROOT).as_posix()}/top200.parquet sha256 {T.sha(run / 'top200.parquet')}; query {CASE}",
        r"\begin{table}[htbp]",
        r"  \centering",
        rf"  \caption[A miss at the first position]{{A miss at the first position, development case \emph{{tesis}} {record}: its facts and the system's first three suggestions. The article the court cited is in bold.}}",
        r"  \label{tab:failure-example}",
        r"  \small",
        rf"  \parbox{{\textwidth}}{{\emph{{{facts}}}}}\par\medskip",
        r"  \begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{0.9cm} >{\raggedright\arraybackslash}p{4.4cm} >{\raggedright\arraybackslash}X@{}}",
        r"    \toprule",
        r"    Rank & Article & Opening words \\",
        r"    \midrule",
        *rows,
        r"    \bottomrule",
        r"  \end{tabularx}",
        r"\end{table}",
        "",
    ])
    OUT.write_text(body, encoding="utf-8")
    print(body)


if __name__ == "__main__":
    main()
