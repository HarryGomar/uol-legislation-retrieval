"""thesis/evidence/numbers_bsard.tex from research/programs/bsard_outside_20261105/result.json (FRAMING decision 3(d)).

The published values are read from the papers' tables on 5 Nov 2026: Louis, van Dijck and Spanakis 2023, Table 2 (G-DSR,
the best); Louis and Spanakis 2022, Table 2 (trained Siamese bi-encoder, for MRR@100, which the 2023 paper does not report).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
r = json.loads((ROOT / "research/programs/bsard_outside_20261105/result.json").read_text(encoding="utf-8"))
m, c = r["means"], r["ci95"]
f = lambda v: f"{v:.3f}"
rows = {"bsardCases": str(r["questions"]),
        "bsardNdcg": f(m["ndcg_at_10"]), "bsardNdcgLo": f(c["ndcg_at_10"][0]), "bsardNdcgHi": f(c["ndcg_at_10"][1]),
        "bsardMap": f(m["map_at_100"]), "bsardMapLo": f(c["map_at_100"][0]), "bsardMapHi": f(c["map_at_100"][1]),
        "bsardRp": f(m["r_precision"]), "bsardRpLo": f(c["r_precision"][0]), "bsardRpHi": f(c["r_precision"][1]),
        "bsardMrr": f(m["mrr_at_100"]), "bsardRecall": f(m["recall_at_20"]), "bsardTopTen": f"{100 * m['success_at_10']:.0f}\\%",
        "bsardInCorpus": f"{100 * r['share_law_in_corpus']:.0f}\\%",
        "bsardBestMap": "0.471", "bsardBestRp": "0.402", "bsardBestRecall": "0.843", "bsardBestMrr": "0.435"}
head = ["% The model alone on BSARD's test split, asked once. Generated by scripts/bsard_macros.py; do not edit.",
        "% bsardBest*: Louis, van Dijck and Spanakis 2023, Table 2, G-DSR (mAP, mRP, R@100); Louis and Spanakis 2022, Table 2, trained Siamese bi-encoder (MRR@100).",
        "% bsardRecall is Recall@20: the model names 20 articles, so its Recall@100 is the same number. Neither paper reports nDCG@10."]
out = ROOT / "thesis/evidence/numbers_bsard.tex"
out.write_text("\n".join([*head, *[f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in rows.items()]]) + "\n", encoding="utf-8")
print(out.read_text(encoding="utf-8"))
