"""Table 5.1: the ranker's eight sources (PLAN addendum 22; V26 plan, section 2, "5.2 The ranker").

The sources are read from the ranker's receipt (``ft_lean__DEV.json``: the encoder's sources, the dropped sources and the
topic models) and its pipeline manifest (the sources without the encoder), so the list is never typed. Each source has a
plain description below; a source of the receipt without one stops the script. Writes ``thesis/tables/T5_1_sources.tex``.

    py -3.12 scripts/t5_sources.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / "experiments/runs/footing_20261101/dev/store/receipts/rt_lm_tesis__DEV.json"
OUT = ROOT / "thesis/tables/T5_1_sources.tex"
WORD = {5: "five", 8: "eight"}
ENCODER = ("dense_qwen8b", "knn_qwen8b", "proto_qwen8b")      # uol.final.footing.ENCODER

# identifier: (name in the table, what it scores)
TEXT = {
    "L_star": ("Words", "BM25 over Spanish stems and TF-IDF over character sequences, on the article preceded by its heading path"),
    "docexp_bm25": ("Words with past facts", "BM25 over the article extended by the facts of the past cases that cite it"),
    "knn_lex_votes": ("Past cases' votes", "the past cases whose facts share the most words with the case vote for the articles they cited"),
    "proto_tfidf": ("Profile", "the facts of the past cases that cite an article, as one TF-IDF vector, compared with the case's facts"),
    "prior": ("Popularity", "how often past cases cited the article"),
    "dense_qwen8b": ("Encoder", "the cosine of the facts and the article in Qwen3-Embedding-8B"),
    "knn_qwen8b": ("Encoder votes", "the past cases nearest to the facts in the encoder vote for the articles they cited"),
    "proto_qwen8b": ("Encoder profile", "the facts of the past cases that cite an article, as one encoder vector, compared with the case's facts"),
}


def main() -> None:
    r = json.loads(RECEIPT.read_text(encoding="utf-8"))
    man = json.loads(Path(r["inputs"]["pipeline_manifest"]).read_text(encoding="utf-8"))
    args = r["spec"]["adapter_args"]
    drop = set(args.get("drop_sources", []))
    ids = [s for s in [*man["pool"]["sources"], *args["add_sources"]] if s not in drop]
    missing = [s for s in ids if s not in TEXT]
    if missing:
        raise SystemExit(f"no description for {missing}")
    plain = [s for s in ids if s not in ENCODER]
    enc = [s for s in ids if s in ENCODER]
    row = lambda s: f"    {TEXT[s][0]} & {TEXT[s][1]} \\\\"
    tex = "\n".join([
        "% Generated by scripts/t5_sources.py from the ranker's receipt and pipeline manifest; do not edit by hand.",
        r"\begin{table}[htbp]",
        r"  \centering",
        rf"  \caption[The ranker's sources]{{The {WORD.get(len(ids), len(ids))} sources of the ranker and what each scores, and the votes of the older \textit{{tesis}}. Every source scores the whole catalogue for each case. The votes add inputs for the articles of the pool and no article to it.}}",
        r"  \label{tab:sources}",
        r"  \begin{tabularx}{\textwidth}{@{}l >{\raggedright\arraybackslash}X@{}}",
        r"    \toprule",
        r"    Source & What it scores \\",
        r"    \midrule",
        rf"    \multicolumn{{2}}{{@{{}}l}}{{\textit{{Without the encoder ({len(plain)})}}}} \\",
        *[row(s) for s in plain],
        r"    \addlinespace[2pt]",
        rf"    \multicolumn{{2}}{{@{{}}l}}{{\textit{{With Qwen3-Embedding-8B ({len(enc)})}}}} \\",
        *[row(s) for s in enc],
        r"    \midrule",
        rf"    Votes of the older \textit{{tesis}} & the older \textit{{tesis}} nearest to the facts vote for the articles they cite; three inputs for each pooled article \\",
        r"    \bottomrule",
        r"  \end{tabularx}",
        r"\end{table}",
        "",
    ])
    OUT.write_text(tex, encoding="utf-8")
    print(tex)


if __name__ == "__main__":
    main()
